export type MessageKey = keyof (typeof messages)['fr']
export type Translator = (key: MessageKey) => string

export const LocaleContext = createContext<{
  locale: Locale
  t: Translator
}>({ locale: 'fr', t: (key) => translate('fr', key) })

export function useTranslation() {
  return useContext(LocaleContext)
}

export function translate(locale: Locale, key: MessageKey): string {
  return messages[locale][key]
}

export function getInitialLocale(): Locale {
  try {
    return window.localStorage.getItem('digitalfootprint.locale') === 'en'
      ? 'en'
      : 'fr'
  } catch {
    return 'fr'
  }
}

export function saveLocale(locale: Locale): void {
  try {
    window.localStorage.setItem('digitalfootprint.locale', locale)
  } catch {
    // The preference is optional; private browsing may disable local storage.
  }
}
